def apply_event(state: dict[str, Any], event: dict[str, Any]) -> dict[str, Any]:
    event_type = require_string(event.get("type"), "event.type", maximum=80)
    normalizing = event_type == "completion-status-normalized" and state.get("status") == "final-approved"
    if (state.get("finalApproval") or state.get("status") == "final-approved") and not normalizing:
        raise RoadmapError(
            "Finally approved roadmaps are immutable; create a successor roadmap."
        )
    if (
        state.get("status") == "completed"
        and event_type != "final-approval-recorded"
    ):
        raise RoadmapError(
            "Completed roadmaps are immutable except for explicit final approval; "
            "create a successor roadmap for new scope."
        )
    handler = EVENT_HANDLERS.get(event_type)
    if not handler:
        raise RoadmapError(f"Unsupported event type: {event_type}.")
    updated = copy.deepcopy(state)
    handler(updated, event)
    timestamp = now_utc()
    updated["updatedAt"] = timestamp
    updated["history"].append(
        {
            "sequence": len(updated["history"]) + 1,
            "type": event_type,
            "eventFingerprint": fingerprint(event),
            "recordedAt": timestamp,
        }
    )
    return updated


def validate_state_shape(repo: Path, state: dict[str, Any]) -> None:
    allowed = {
        "schemaVersion",
        "name",
        "slug",
        "objective",
        "createdAt",
        "updatedAt",
        "paths",
        "status",
        "discovery",
        "decisions",
        "increments",
        "roadmapApproval",
        "currentIncrementId",
        "chunks",
        "feedback",
        "evidence",
        "blockers",
        "resumeAudits",
        "history",
        "completion",
        "finalApproval",
        "evidencePolicy",
        "completionSuite",
        "humanAcceptanceTransfers",
        "acceptanceScopeRevisions",
        "legacyAcceptanceScopeRevisions",
        "technicalAcceptanceRevisions",
    }
    reject_unknown(state, allowed, "state")
    for revision in require_list(state.get("technicalAcceptanceRevisions", []), "state.technicalAcceptanceRevisions"):
        revision = validate_technical_replacement(revision, "technical revision")
        if state.get("evidencePolicy") != "control-plane-v1":
            raise RoadmapError("Technical acceptance revisions retain governed completion policy.")
        increment = find_increment(state, revision["incrementId"])
        if not any(c["id"] == revision["originalCriterion"]["id"] and c["qualification"] == "controlled-environment"
                   for c in increment["acceptanceCriteria"]):
            raise RoadmapError("Amended technical identity and qualification must remain active.")
    for transfer in require_list(state.get("humanAcceptanceTransfers", []), "state.humanAcceptanceTransfers"):
        reject_unknown(transfer, {"incrementId", "criteria", "originalPlan", "previousApproval", "authorityRef", "summary", "status", "recordedAt"}, "transfer")
        increment = find_increment(state, require_identifier(transfer.get("incrementId"), "transfer.incrementId"))
        require_identifier(transfer.get("authorityRef"), "transfer.authorityRef")
        require_string(transfer.get("summary"), "transfer.summary")
        require_string(transfer.get("recordedAt"), "transfer.recordedAt", maximum=80)
        require_object(transfer.get("originalPlan"), "transfer.originalPlan")
        require_object(transfer.get("previousApproval"), "transfer.previousApproval")
        if transfer.get("status") != "offline-user-owned":
            raise RoadmapError("Transferred human acceptance must remain offline-user-owned.")
        for c in require_list(transfer.get("criteria"), "transfer.criteria", minimum=1):
            archived = validate_criterion(c, "transfer.criterion")
            if archived["id"] in {item["id"] for item in increment["acceptanceCriteria"]}:
                raise RoadmapError("Transferred human acceptance cannot remain an active criterion.")
    revisions = [(r, "control-plane-v1") for r in require_list(state.get("acceptanceScopeRevisions", []), "state.acceptanceScopeRevisions")]
    revisions += [(r, None) for r in require_list(state.get("legacyAcceptanceScopeRevisions", []), "state.legacyAcceptanceScopeRevisions")]
    for revision, expected_policy in revisions:
        revision = require_object(revision, "revision")
        reject_unknown(revision, {"incrementId", "removedCriteria", "replacedCriteria", "originalPlan", "previousApproval",
                                  "authorityRef", "summary", "status", "recordedAt"}, "revision")
        increment = find_increment(state, require_identifier(revision.get("incrementId"), "revision.incrementId"))
        if state.get("evidencePolicy") != expected_policy or revision.get("status") != "offline-user-owned":
            raise RoadmapError("Acceptance scope revision must retain its original evidence policy and offline ownership.")
        require_identifier(revision.get("authorityRef"), "revision.authorityRef")
        require_string(revision.get("summary"), "revision.summary")
        require_string(revision.get("recordedAt"), "revision.recordedAt", maximum=80)
        require_object(revision.get("originalPlan"), "revision.originalPlan")
        require_object(revision.get("previousApproval"), "revision.previousApproval")
        active_ids = {c["id"] for c in increment["acceptanceCriteria"]}
        ids = []
        for c in require_list(revision.get("removedCriteria"), "revision.removedCriteria"):
            c = validate_criterion(c, "revision.removedCriterion")
            if c["id"] in active_ids or c["id"].startswith("security-") or c["qualification"] != "controlled-environment":
                raise RoadmapError("Retired human scope cannot be active, local or security acceptance.")
            ids.append(c["id"])
        for r in require_list(revision.get("replacedCriteria"), "revision.replacedCriteria"):
            r = require_object(r, "revision.replacement")
            reject_unknown(r, {"original", "revised", "humanScope"}, "revision.replacement")
            original = validate_criterion(r.get("original"), "revision.original")
            revised = validate_criterion(r.get("revised"), "revision.revised")
            require_string(r.get("humanScope"), "revision.humanScope")
            if original["id"] != revised["id"] or original["id"].startswith("security-") or original["qualification"] != "controlled-environment" or revised["qualification"] != "controlled-environment" or original == revised:
                raise RoadmapError("Archived mixed scope must retain the original technical identity and qualification.")
            ids.append(original["id"])
        if not ids or len(ids) != len(set(ids)):
            raise RoadmapError("Archived scope requires unique criterion identities.")
    if state.get("schemaVersion") != SCHEMA_VERSION:
        raise RoadmapError(
            f"Unsupported state schema version: {state.get('schemaVersion')}."
        )
    require_string(state.get("name"), "state.name", maximum=200)
    require_identifier(state.get("slug"), "state.slug")
    require_string(state.get("objective"), "state.objective")
    require_string(state.get("createdAt"), "state.createdAt", maximum=80)
    require_string(state.get("updatedAt"), "state.updatedAt", maximum=80)
    require_string(state.get("status"), "state.status", maximum=80)
    if state.get("evidencePolicy") not in {None, "control-plane-v1"}:
        raise RoadmapError("Unsupported roadmap evidence policy.")
    if state.get("completionSuite") not in {None, "standardande2e", "all"}:
        raise RoadmapError("Unsupported roadmap completion suite.")
    paths = require_object(state.get("paths"), "state.paths")
    reject_unknown(paths, {"state", "roadmap", "report"}, "state.paths")
    normalized_paths = {
        key: safe_relative_path(repo, paths.get(key), f"state.paths.{key}")
        for key in ("state", "roadmap", "report")
    }
    if len(set(normalized_paths.values())) != 3:
        raise RoadmapError("State, roadmap, and report paths must be distinct.")
    for key in (
        "decisions",
        "increments",
        "chunks",
        "feedback",
        "evidence",
        "blockers",
        "resumeAudits",
        "history",
    ):
        require_list(state.get(key), f"state.{key}")
    discovery = state.get("discovery")
    if discovery is not None:
        discovery = require_object(discovery, "state.discovery")
        if discovery.get("securityImpact") is not None:
            validate_security_impact(
                discovery["securityImpact"], "state.discovery.securityImpact"
            )
            if state["increments"]:
                require_security_acceptance_criterion(
                    state["increments"], "state.increments"
                )
    if state.get("currentIncrementId") is not None:
        find_increment(
            state,
            require_identifier(
                state["currentIncrementId"], "state.currentIncrementId"
            ),
        )
    if state["roadmapApproval"] and not approval_is_current(state):
        raise RoadmapError("Stored roadmap approval is stale.")
    final_approval = state.get("finalApproval")
    if final_approval is not None:
        final_approval = require_object(final_approval, "state.finalApproval")
        reject_unknown(
            final_approval, {"note", "approvedAt"}, "state.finalApproval"
        )
        require_string(final_approval.get("note"), "state.finalApproval.note")
        require_string(
            final_approval.get("approvedAt"),
            "state.finalApproval.approvedAt",
            maximum=80,
        )
        if state["status"] not in {"completed", "final-approved"}:
            raise RoadmapError(
                "Final approval requires completed status (or legacy final-approved)."
            )
        require_finalized_completion(state)
    elif state["status"] == "final-approved":
        raise RoadmapError(
            "state.finalApproval is required for a final-approved roadmap."
        )


def render_sources(
    sources: list[dict[str, str]], from_path: str
) -> list[str]:
    lines = []
    for source in sources:
        title = markdown(source["title"])
        if source.get("url"):
            source_url = source["url"]
            parsed = urlsplit(source_url)
            rendered_url = (
                source_url
                if parsed.scheme or source_url.startswith(("#", "?"))
                else relative_markdown_link(from_path, source_url)
            )
            title = f"[{title}](<{rendered_url}>)"
        note = f" - {markdown(source['note'])}" if source.get("note") else ""
        lines.append(f"- {title}{note}")
    return lines or ["None recorded."]


def evidence_label(state: dict[str, Any], increment_id: str, criterion_id: str) -> str:
    evidence = latest_criterion_evidence(state, increment_id, criterion_id)
    if not evidence:
        return "not recorded"
    return f"{evidence['outcome']} ({evidence['kind']})"


def render_roadmap(state: dict[str, Any]) -> str:
    lines = [
        GENERATED_NOTICE,
        "",
        f"# {state['name']} Implementation Roadmap",
        "",
        f"- Status: `{state['status']}`",
        f"- Updated: `{state['updatedAt']}`",
        "",
        "## Objective",
        "",
        state["objective"],
        "",
        "## Discovery",
        "",
    ]
    discovery = state.get("discovery")
    if discovery:
        lines.append(discovery["summary"])
        security_impact = discovery.get("securityImpact")
        if security_impact:
            lines.extend(
                [
                    "",
                    "### Security impact",
                    "",
                    f"- Disposition: `{security_impact['disposition']}`",
                    f"- Summary: {security_impact['summary']}",
                ]
            )
            if security_impact["disposition"] == "security-relevant":
                for title, key in (
                    ("Protected assets", "assets"),
                    ("Trust boundaries", "trustBoundaries"),
                    ("Abuse and failure cases", "abuseCases"),
                    ("Controls", "controls"),
                    ("Verification", "verification"),
                    ("Residual risks", "residualRisks"),
                ):
                    lines.extend([f"- {title}:"])
                    lines.extend(
                        f"  - {item}" for item in security_impact.get(key, [])
                    )
                    if not security_impact.get(key):
                        lines.append("  - None.")
        lines.extend(
            [
                "",
                "### Constraints",
                "",
                *bullet_lines(discovery["constraints"]),
                "",
                "### Sources",
                "",
                *render_sources(
                    discovery["sources"], state["paths"]["roadmap"]
                ),
            ]
        )
    else:
        lines.append("Discovery has not been recorded.")
    lines.extend(["", "## High-level decisions", ""])
    if not state["decisions"]:
        lines.append("No high-level decision has been recorded.")
    for decision in state["decisions"]:
        selected = decision.get("selectedOptionId") or "awaiting approval"
        lines.extend(
            [
                f"### {decision['title']}",
                "",
                decision["question"],
                "",
                decision["context"],
                "",
                f"- Status: `{decision['status']}`",
                f"- Selected option: `{selected}`",
                "",
                "| Option | Summary | Recommended | Tradeoffs | Consequences |",
                "| --- | --- | --- | --- | --- |",
            ]
        )
        for option in decision["options"]:
            lines.append(
                "| "
                + " | ".join(
                    [
                        markdown(f"{option['label']} ({option['id']})"),
                        markdown(option["summary"]),
                        "yes" if option["recommended"] else "no",
                        markdown("; ".join(option["tradeoffs"]) or "None"),
                        markdown("; ".join(option["consequences"]) or "None"),
                    ]
                )
                + " |"
            )
        lines.append("")
    lines.extend(["## Increment map", ""])
    if state["increments"]:
        lines.extend(
            [
                "| Increment | Outcome | Dependencies | Status |",
                "| --- | --- | --- | --- |",
            ]
        )
        for increment in state["increments"]:
            dependencies = ", ".join(increment["dependsOn"]) or "None"
            lines.append(
                f"| {increment['number']}: {markdown(increment['title'])} "
                f"| {markdown(increment['objective'])} | {dependencies} "
                f"| `{increment['status']}` |"
            )
    else:
        lines.append("The increment roadmap has not been defined.")
    for increment in state["increments"]:
        lines.extend(
            [
                "",
                f"## Increment {increment['number']}: {increment['title']}",
                "",
                f"- Id: `{increment['id']}`",
                f"- Status: `{increment['status']}`",
                "- Dependencies: "
                + (
                    ", ".join(f"`{item}`" for item in increment["dependsOn"])
                    or "None"
                ),
                "",
                increment["objective"],
                "",
                "### Work packages",
                "",
            ]
        )
        if increment["workPackages"]:
            if any(r["incrementId"] == increment["id"] for r in state.get("acceptanceScopeRevisions", []) + state.get("legacyAcceptanceScopeRevisions", [])):
                lines.extend(["Human portions of the original work packages, deliverables, verification and completed plan below are superseded by the exact offline scope archive. They remain historical approved intent; only the current technical acceptance criteria govern future qualification. No test pass is asserted.", ""])
            lines.extend(
                f"- **{item['title']}** (`{item['id']}`): {item['outcome']}"
                for item in increment["workPackages"]
            )
        else:
            lines.append("None recorded.")
        lines.extend(
            [
                "",
                "### Deliverables",
                "",
                *bullet_lines(increment["deliverables"]),
                "",
                "### Acceptance criteria",
                "",
                "| Criterion | Qualification | Latest evidence |",
                "| --- | --- | --- |",
            ]
        )
        for criterion in increment["acceptanceCriteria"]:
            lines.append(
                f"| `{criterion['id']}`: {markdown(criterion['description'])} "
                f"| {criterion['qualification']} "
                f"| {evidence_label(state, increment['id'], criterion['id'])} |"
            )
        technical_revisions = [r for r in state.get("technicalAcceptanceRevisions", []) if r["incrementId"] == increment["id"]]
        if technical_revisions:
            lines.extend(["", "### Technical policy amendment history", ""])
            for revision in technical_revisions:
                lines.append(f"- {markdown(revision['summary'])} (`{revision['authorityRef']}`); no test pass or completion is asserted.")
                lines.append(f"  - Original `{revision['originalCriterion']['id']}`: {markdown(revision['originalCriterion']['description'])}")
                lines.append(f"  - Superseded requirements: {markdown('; '.join(revision['supersededRequirements']))}")
                lines.append(f"  - Retained requirements: {markdown('; '.join(revision['retainedRequirements']))}")
        transfers = [t for t in state.get("humanAcceptanceTransfers", []) if t["incrementId"] == increment["id"]]
        if transfers:
            lines.extend(["", "### Human acceptance handled offline", ""])
            for transfer in transfers:
                lines.append(f"- {markdown(transfer['summary'])} (`{transfer['authorityRef']}`)")
                lines.extend(f"  - `{c['id']}`: {markdown(c['description'])} — offline user-owned; no test pass asserted." for c in transfer["criteria"])
        revisions = [r for r in state.get("acceptanceScopeRevisions", []) + state.get("legacyAcceptanceScopeRevisions", []) if r["incrementId"] == increment["id"]]
        if revisions:
            lines.extend(["", "### Human scope handled offline", ""])
            for revision in revisions:
                lines.append(f"- {markdown(revision['summary'])} (`{revision['authorityRef']}`)")
                lines.extend(f"  - `{c['id']}`: {markdown(c['description'])} — offline user-owned; no test pass asserted." for c in revision["removedCriteria"])
                lines.extend(f"  - Human portion of `{r['original']['id']}`: {markdown(r['humanScope'])} — offline user-owned; technical criterion retained; no test pass asserted." for r in revision["replacedCriteria"])
        lines.extend(
            [
                "",
                "### Verification",
                "",
                *bullet_lines(increment["verification"]),
                "",
                "### Rollback",
                "",
                increment["rollback"],
                "",
                "### Excluded",
                "",
                *bullet_lines(increment["excluded"]),
            ]
        )
    return "\n".join(lines).rstrip() + "\n"


def next_checkpoint(state: dict[str, Any]) -> str:
    if state.get("finalApproval"):
        return ("Final approval recorded and the temporary report removed; create a "
                "successor roadmap for new scope.")
    status = state["status"]
    if status == "discovery":
        return "Inspect the repository and record discovery."
    if status in {"decision-options", "decision-approval"}:
        return (
            "Present two or three high-level options and obtain explicit user approval."
        )
    if status in {"roadmap-drafting", "roadmap-review"}:
        return "Define the increments and obtain explicit roadmap approval."
    if status == "approval-required":
        return "Reconcile feedback and obtain renewed user approval before continuing."
    if status == "ready":
        return (
            "Start the next pending increment, then research and plan it before editing."
        )
    if status == "executing":
        return "Complete the active planned chunk and update this report."
    if status == "blocked":
        return "Resolve the recorded blocker and complete a resume reconciliation."
    if status == "implementation-complete-qualification-pending":
        return "Collect the outstanding controlled-environment evidence."
    if status == "roadmap-ready-to-close":
        return "Review final evidence and record roadmap completion."
    if status == "completed":
        return (
            "Present the final report and wait for explicit overall approval before "
            "recording final approval and removing the temporary report."
        )
    if status == "final-approved":
        return (
            "Final approval recorded and the temporary report removed; create a "
            "successor roadmap for new scope."
        )
    return "Review the state and choose the next approved transition."


def compact_markdown(value: Any, maximum: int = 220) -> str:
    text = markdown(value)
    if len(text) <= maximum:
        return text
    return text[: maximum - 3].rstrip() + "..."


def increment_evidence_summary(
    state: dict[str, Any], increment: dict[str, Any]
) -> str:
    counts = {"passed": 0, "pending": 0, "failed": 0, "missing": 0}
    for criterion in increment["acceptanceCriteria"]:
        evidence = latest_criterion_evidence(
            state, increment["id"], criterion["id"]
        )
        key = evidence["outcome"] if evidence else "missing"
        counts[key] += 1
    return (
        f"{counts['passed']} passed, {counts['pending']} pending, "
        f"{counts['failed']} failed, {counts['missing']} missing"
    )


def render_report(state: dict[str, Any]) -> str:
    roadmap_link = relative_markdown_link(
        state["paths"]["report"], state["paths"]["roadmap"]
    )
    lines = [
        GENERATED_NOTICE,
        "",
        f"# {state['name']} Implementation Report",
        "",
        f"- Roadmap: [{state['name']} implementation roadmap]({roadmap_link})",
        f"- Status: `{state['status']}`",
        f"- Current increment: `{state.get('currentIncrementId') or 'none'}`",
        f"- Updated: `{state['updatedAt']}`",
        "",
        "## Next checkpoint",
        "",
        next_checkpoint(state),
        "",
        "## Increment status",
        "",
    ]
    if state["increments"]:
        lines.extend(
            [
                "| Increment | Status | Chunks | Criteria |",
                "| --- | --- | --- | --- |",
            ]
        )
        for increment in state["increments"]:
            planned = len((increment.get("plan") or {}).get("chunks", []))
            chunks = (
                f"{len(increment['completedChunks'])}/{planned}"
                if planned
                else str(len(increment["completedChunks"]))
            )
            lines.append(
                f"| {increment['number']}: {markdown(increment['title'])} "
                f"| `{increment['status']}` | {chunks} "
                f"| {increment_evidence_summary(state, increment)} |"
            )
    else:
        lines.append("No increments defined.")
    active = None
    if state.get("currentIncrementId"):
        active = current_increment(state)
    lines.extend(["", "## Current work", ""])
    if active and active.get("plan"):
        next_chunk = next(
            (
                chunk
                for chunk in active["plan"]["chunks"]
                if chunk["id"] not in active["completedChunks"]
            ),
            None,
        )
        lines.append(compact_markdown(active["plan"]["summary"]))
        if next_chunk:
            lines.append(
                f"- Next chunk: **{next_chunk['title']}** "
                f"(`{next_chunk['id']}`) - "
                f"{compact_markdown(next_chunk['outcome'], 180)}"
            )
        else:
            lines.append("- Next chunk: none; complete increment verification.")
    else:
        lines.append("No active implementation plan.")
    lines.extend(["", "## Recent progress", ""])
    if state["chunks"]:
        lines.extend(
            [
                "| Completed | Increment / chunk | Summary |",
                "| --- | --- | --- |",
            ]
        )
        for chunk in state["chunks"][-5:]:
            lines.append(
                f"| `{chunk['completedAt']}` "
                f"| `{chunk['incrementId']}/{chunk['chunkId']}` "
                f"| {compact_markdown(chunk['summary'], 180)} |"
            )
    else:
        lines.append("No coherent work chunk has been completed.")
    lines.extend(["", "## Recent feedback", ""])
    if state["feedback"]:
        addressed = {
            feedback_id
            for chunk in state["chunks"]
            for feedback_id in chunk["feedbackAddressed"]
        }
        lines.extend(
            [
                "| Id | Status | Summary |",
                "| --- | --- | --- |",
            ]
        )
        for item in state["feedback"][-5:]:
            status = "addressed" if item["id"] in addressed else item["disposition"]
            lines.append(
                f"| `{item['id']}` | {status} "
                f"| {compact_markdown(item['summary'], 180)} |"
            )
    else:
        lines.append("None recorded.")
    lines.extend(["", "## Open blockers", ""])
    open_blockers = [
        blocker for blocker in state["blockers"] if blocker["status"] != "resolved"
    ]
    if open_blockers:
        for blocker in open_blockers[-3:]:
            lines.append(
                f"- **{blocker['id']}** ({blocker['kind']}, {blocker['status']}): "
                f"{compact_markdown(blocker['summary'], 140)} Required action: "
                f"{compact_markdown(blocker['requiredAction'], 140)}"
            )
    else:
        lines.append("No blockers recorded.")
    if state.get("completion"):
        lines.extend(
            [
                "",
                "## Completion",
                "",
                compact_markdown(state["completion"]["summary"]),
                "",
                f"Completed at `{state['completion']['completedAt']}`.",
            ]
        )
    return "\n".join(lines).rstrip() + "\n"


def document_contents(state: dict[str, Any]) -> dict[str, str]:
    contents = {
        state["paths"]["roadmap"]: render_roadmap(state),
    }
    if not state.get("finalApproval"):
        contents[state["paths"]["report"]] = render_report(state)
    return contents


def ensure_documents_match(repo: Path, state: dict[str, Any]) -> None:
    mismatches = []
    for relative, expected in document_contents(state).items():
        path = repo / relative
        try:
            actual = path.read_text(encoding="utf-8")
        except OSError:
            mismatches.append(relative)
            continue
        if normalize_text(actual) != expected:
            mismatches.append(relative)
    if state.get("finalApproval") and (repo / state["paths"]["report"]).exists():
        mismatches.append(state["paths"]["report"])
    if mismatches:
        raise RoadmapError(
            "Generated document drift detected: "
            + ", ".join(mismatches)
            + ". Run the render command to restore documents from state."
        )


def remove_generated_report(path: Path) -> None:
    if not path.exists():
        return
    try:
        content = path.read_text(encoding="utf-8")
    except OSError as error:
        raise RoadmapError(f"Unable to inspect temporary report: {error}") from error
    if not normalize_text(content).startswith(GENERATED_NOTICE):
        raise RoadmapError(
            "Refusing to remove a temporary report without the generated notice."
        )
    try:
        path.unlink()
    except OSError as error:
        raise RoadmapError(f"Unable to remove temporary report: {error}") from error


def write_project_files(
    repo: Path,
    state: dict[str, Any],
    *,
    previous_report_path: str | None = None,
) -> None:
    state_content = (
        json.dumps(state, indent=2, ensure_ascii=True, sort_keys=True) + "\n"
    )
    atomic_write(repo / state["paths"]["state"], state_content)
    for relative, content in document_contents(state).items():
        atomic_write(repo / relative, content)
    if previous_report_path and previous_report_path != state["paths"]["report"]:
        remove_generated_report(repo / previous_report_path)
    if state.get("finalApproval"):
        remove_generated_report(repo / state["paths"]["report"])


def initial_state(repo: Path, config: dict[str, Any]) -> dict[str, Any]:
    reject_unknown(
        config,
        {
            "name",
            "slug",
            "objective",
            "statePath",
            "roadmapPath",
            "reportPath",
            "completionSuite",
        },
        "config",
    )
    name = require_string(config.get("name"), "config.name", maximum=200)
    slug = require_identifier(config.get("slug"), "config.slug")
    objective = require_string(config.get("objective"), "config.objective")
    paths = {
        "state": safe_relative_path(
            repo,
            config.get(
                "statePath", f".implementation-roadmaps/{slug}/state.json"
            ),
            "config.statePath",
        ),
        "roadmap": safe_relative_path(
            repo,
            config.get(
                "roadmapPath", f"docs/{slug}-implementation-roadmap.md"
            ),
            "config.roadmapPath",
        ),
        "report": safe_relative_path(
            repo,
            temporary_report_path(
                config.get(
                    "reportPath",
                    f"docs/tmp/{slug}-implementation-report.md",
                ),
                "config.reportPath",
            ),
            "config.reportPath",
        ),
    }
    if len(set(paths.values())) != 3:
        raise RoadmapError("State, roadmap, and report paths must be distinct.")
    existing = [
        relative for relative in paths.values() if (repo / relative).exists()
    ]
    if existing:
        raise RoadmapError(
            "Refusing to overwrite existing file(s): " + ", ".join(existing)
        )
    timestamp = now_utc()
    state = {
        "schemaVersion": SCHEMA_VERSION,
        "name": name,
        "slug": slug,
        "objective": objective,
        "createdAt": timestamp,
        "updatedAt": timestamp,
        "paths": paths,
        "status": "discovery",
        "discovery": None,
        "decisions": [],
        "increments": [],
        "roadmapApproval": None,
        "currentIncrementId": None,
        "chunks": [],
        "feedback": [],
        "evidence": [],
        "blockers": [],
        "resumeAudits": [],
        "history": [],
        "completion": None,
        "finalApproval": None,
    }
    if (repo / "dev-tools/helpers/development_control_plane.py").is_file():
        if not paths["state"].startswith(".implementation-roadmaps/") or not paths["state"].endswith("/state.json"):
            raise RoadmapError("The control-plane adapter requires .implementation-roadmaps/<slug>/state.json.")
        state["evidencePolicy"] = "control-plane-v1"
        state["completionSuite"] = config.get("completionSuite", "standardande2e")
    validate_state_shape(repo, state)
    return state


def resolve_repo(value: str) -> Path:
    repo = Path(value).resolve()
    if not repo.is_dir():
        raise RoadmapError(f"Repository directory does not exist: {repo}")
    return repo


def load_state(repo: Path, value: str) -> tuple[Path, dict[str, Any]]:
    relative = safe_relative_path(repo, value, "--state")
    path = repo / relative
    state = read_json(path, "state")
    validate_state_shape(repo, state)
    if state["paths"]["state"] != relative:
        raise RoadmapError("--state does not match state.paths.state.")
    return path, state


def result_payload(repo: Path, state: dict[str, Any]) -> dict[str, Any]:
    return {
        "status": state["status"],
        "currentIncrementId": state.get("currentIncrementId"),
        "statePath": str((repo / state["paths"]["state"]).resolve()),
        "roadmapPath": str((repo / state["paths"]["roadmap"]).resolve()),
        "reportPath": (
            None
            if state.get("finalApproval")
            else str((repo / state["paths"]["report"]).resolve())
        ),
        "reportAvailable": not bool(state.get("finalApproval")),
        "roadmapFingerprint": (
            roadmap_fingerprint(state) if state["increments"] else None
        ),
    }


def command_init(args: argparse.Namespace) -> dict[str, Any]:
    repo = resolve_repo(args.repo)
    config = read_json(Path(args.config).resolve(), "config")
    state_path = config.get("statePath", f".implementation-roadmaps/{config['slug']}/state.json")
    safe_relative_path(repo, state_path, "statePath")
    with publication_lock(repo, state_path) as journal:
        recover_publication(repo, journal, state_path)
        state = initial_state(repo, config)
        atomic_write(journal, canonical_json({"before": fingerprint(None), "successor": state, "previousReport": None}))
        write_project_files(repo, state)
        journal.unlink()
    return result_payload(repo, state)


def command_apply(args: argparse.Namespace) -> dict[str, Any]:
    repo = resolve_repo(args.repo)
    state_path = safe_relative_path(repo, args.state, "--state")
    with publication_lock(repo, state_path) as journal:
        if not args.dry_run:
            recover_publication(repo, journal, state_path)
        _, state = load_state(repo, args.state)
        before = fingerprint(state)
        ensure_documents_match(repo, state)
        event = read_json(Path(args.event_file).resolve(), "event")
        if event.get("type") == "increment-completed":
            require_control_completion(repo, state)
        elif event.get("type") == "increment-qualified":
            target_id = require_identifier(event.get("incrementId"), "event.incrementId")
            work_id = require_identifier(event.get("workId"), "event.workId")
            completion = require_control_completion(repo, state, increment_id=target_id, work_id=work_id)
            if completion is None or any(event.get(k) != v for k, v in completion.items()):
                raise RoadmapError("Qualification must consume the exact current target work, receipt and independent review.")
        elif event.get("type") == "roadmap-completed":
            require_control_completion(repo, state, overall=True)
        updated = apply_event(state, event)
        validate_state_shape(repo, updated)
        if not args.dry_run:
            if fingerprint(read_json(repo / state_path, "state")) != before:
                raise RoadmapError("State revision changed before publication; reconcile first.")
            atomic_write(journal, canonical_json({"before": before, "successor": updated, "previousReport": state["paths"]["report"]}))
            write_project_files(repo, updated, previous_report_path=state["paths"]["report"])
            journal.unlink()
    result = result_payload(repo, updated)
    result["dryRun"] = args.dry_run
    result["eventFingerprint"] = fingerprint(event)
    return result


def command_validate(args: argparse.Namespace) -> dict[str, Any]:
    repo = resolve_repo(args.repo)
    _, state = load_state(repo, args.state)
    ensure_documents_match(repo, state)
    result = result_payload(repo, state)
    result["valid"] = True
    return result


def command_render(args: argparse.Namespace) -> dict[str, Any]:
    repo = resolve_repo(args.repo)
    state_path = safe_relative_path(repo, args.state, "--state")
    with publication_lock(repo, state_path) as journal:
        if not args.dry_run:
            recover_publication(repo, journal, state_path)
        _, state = load_state(repo, args.state)
        if not args.dry_run:
            write_project_files(repo, state)
    result = result_payload(repo, state)
    result["dryRun"] = args.dry_run
    return result


def command_status(args: argparse.Namespace) -> dict[str, Any]:
    repo = resolve_repo(args.repo)
    _, state = load_state(repo, args.state)
    result = result_payload(repo, state)
    result["nextCheckpoint"] = next_checkpoint(state)
    return result


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Maintain an approval-gated implementation roadmap."
    )
    subparsers = parser.add_subparsers(dest="command", required=True)

    init_parser = subparsers.add_parser(
        "init", help="Create roadmap state and documents."
    )
    init_parser.add_argument("--repo", default=".")
    init_parser.add_argument("--config", required=True)
    init_parser.set_defaults(handler=command_init)

    for name, handler, help_text in (
        ("apply", command_apply, "Apply one validated event."),
        (
            "validate",
            command_validate,
            "Validate state and generated documents.",
        ),
        ("render", command_render, "Restore generated documents from state."),
        ("status", command_status, "Show the next workflow checkpoint."),
    ):
        subparser = subparsers.add_parser(name, help=help_text)
        subparser.add_argument("--repo", default=".")
        subparser.add_argument("--state", required=True)
        if name in {"apply", "render"}:
            subparser.add_argument("--dry-run", action="store_true")
        if name == "apply":
            subparser.add_argument("--event-file", required=True)
        subparser.set_defaults(handler=handler)
    return parser


def main(argv: list[str] | None = None) -> int:
    parser = build_parser()
    args = parser.parse_args(argv)
    try:
        result = args.handler(args)
    except RoadmapError as error:
        print(f"roadmap.py: error: {error}", file=sys.stderr)
        return 2
    except (KeyError, TypeError, IndexError) as error:
        print(
            f"roadmap.py: error: malformed roadmap state or event: {error}",
            file=sys.stderr,
        )
        return 2
    print(json.dumps(result, indent=2, ensure_ascii=True, sort_keys=True))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
