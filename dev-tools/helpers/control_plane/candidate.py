"""Content-addressed source snapshots; lifecycle projections are separately bound."""
from __future__ import annotations

import hashlib
import os
import subprocess
from pathlib import Path

from .common import digest, read_json, refuse, relative
from .storage import confined_path

MAX_FILES = 20000
MAX_SOURCE_BYTES = 512 * 1024 * 1024


def git(root: Path, *args: str) -> bytes:
    env = {k: v for k, v in os.environ.items() if not k.startswith("GIT_")}
    env.update(GIT_CONFIG_NOSYSTEM="1", GIT_NO_REPLACE_OBJECTS="1")
    try:
        r = subprocess.run(["git", "-c", "core.hooksPath=" + ("NUL" if os.name == "nt" else "/dev/null"), *args], cwd=root, env=env, capture_output=True, timeout=20)
    except (OSError, subprocess.TimeoutExpired):
        refuse("candidate.git-unavailable", "Git could not establish candidate identity.")
    if r.returncode or len(r.stdout) > 8 * 1024 * 1024:
        refuse("candidate.git-refused", "Git could not establish a bounded repository fact.")
    return r.stdout


def managed_projection(root: Path, path: str) -> bool:
    if path.startswith((".local-codex/", "artifacts/", "docs/tmp/", ".implementation-roadmaps/")):
        return True
    if path.startswith("docs/") and path.endswith("-implementation-roadmap.md"):
        p = confined_path(root, path)
        if p.is_file():
            with p.open("rb") as stream:
                return stream.read(150).startswith(b"<!-- Generated by manage-implementation-roadmaps.")
    return False


def snapshot(root: Path) -> dict:
    root = root.resolve()
    actual = Path(os.fsdecode(git(root, "rev-parse", "--show-toplevel")).strip()).resolve()
    if actual != root:
        refuse("candidate.root", "Git resolved a different repository.")
    paths = sorted(set(os.fsdecode(p) for p in git(root, "ls-files", "-c", "-o", "--exclude-standard", "-z").split(b"\0") if p))
    if len(paths) > MAX_FILES:
        refuse("candidate.capacity", "Candidate file count exceeds the supported bound.")
    files = {}
    total = 0
    for name in paths:
        relative(name)
        if managed_projection(root, name):
            continue
        path = confined_path(root, name)
        if path.is_symlink():
            refuse("candidate.symlink", "Source symlinks require an explicit qualified adapter.")
        if not path.exists():
            continue  # deletion remains visible against the baseline map
        if not path.is_file():
            refuse("candidate.file-type", "Candidate contains an unsupported source object.")
        before = path.stat()
        total += before.st_size
        if total > MAX_SOURCE_BYTES or before.st_size > 32 * 1024 * 1024:
            refuse("candidate.capacity", "Candidate source bytes exceed the supported bound.")
        h = hashlib.sha256()
        with path.open("rb") as stream:
            while block := stream.read(65536):
                h.update(block)
        after = path.stat()
        if (before.st_size, before.st_mtime_ns) != (after.st_size, after.st_mtime_ns):
            refuse("candidate.drift", "Source changed while capturing the candidate.")
        files[name] = h.hexdigest()
    return {"schema_version": "source-snapshot-v1", "head": os.fsdecode(git(root, "rev-parse", "HEAD")).strip(), "files": files, "source_digest": digest(files)}


def changed(before: dict, after: dict) -> list[str]:
    return sorted(p for p in before.keys() | after.keys() if before.get(p) != after.get(p))


def roadmap_authority(root: Path, binding: dict | None) -> str | None:
    if not binding:
        return None
    if set(binding) != {"state_path", "increment_id"}:
        refuse("authority.binding", "Roadmap binding requires state_path and increment_id.")
    path = relative(binding["state_path"])
    if not path.startswith(".implementation-roadmaps/") or not path.endswith("/state.json"):
        refuse("authority.binding", "Use the canonical roadmap state path.")
    state = read_json(confined_path(root, path))
    # Load the existing planning authority, without launching commands or recording approval.
    import importlib.util
    import sys
    script = root / "skills/manage-implementation-roadmaps/scripts/roadmap.py"
    sys.path.insert(0, str(script.parent))
    try:
        spec = importlib.util.spec_from_file_location("aisb_roadmap_authority", script)
        module = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(module)
        module.validate_state_shape(root, state)
        approved = module.approval_is_current(state)
        overall_ready = module.implementation_ready_for_overall(state)
    except Exception:
        refuse("authority.invalid", "The roadmap authority is missing, malformed or stale.")
    finally:
        sys.path.pop(0)
    overall = binding["increment_id"] == "overall"
    active = overall_ready if overall else (state.get("currentIncrementId") == binding["increment_id"] and state.get("status") == "executing")
    if state["paths"]["state"] != path or not approved or not active:
        refuse("authority.not-active", "The work is not bound to the active approved roadmap increment.")
    return state["roadmapApproval"]["fingerprint"]
